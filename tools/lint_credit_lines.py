"""A line that credits a tool for a change is refused by its shape, not by the tool's name (ADR 0013).

    python3 tools/lint_credit_lines.py --range main..HEAD      # every commit message a branch adds
    python3 tools/lint_credit_lines.py --file description.md   # one text: a description, a message

`tools/lint_commits.py` refuses two trailer keys by name, and the description checker once refused
"Generated with" before nine names. A list is as wide as the tools its writer knew: a footer naming a
tenth tool passed both, planted and measured on 2026-10-14. So the credit is read by the shape every
tool's footer has, whatever the tool is called:

- a **trailer whose key is a credit** — it ends in `-by` or `-with`, or says session, generated,
  assisted or co-author: `Co-authored-by:`, `Generated-by:`, `Assisted-by:`, `Claude-Session:`,
  `Cursor-Session-URL:` — every key but `Signed-off-by:`, which is the signer's own statement;
- a line that **opens with a credit verb and `with`, `by`, `using` or `via` before a name** —
  `Generated with …`, `Co-authored by: …`, `Written using …`, `Powered by …`, `สร้างด้วย …` — after
  any emoji (a `:shortcode:` too), list mark or emphasis, the name on the same line or the next. Any
  name is one, in either case, but a path or a phrase that opens with an article: "generated by the
  build" and "Generated with tools/gen_settings_docs.py" name no tool and pass. After a Thai verb
  the name opens with a Latin letter, as tool names do, so "สร้างโดยสคริปต์" passes;
- a **link alone on its line** — bare, in `<…>`, as `[text](link)`, or after a `Key:` — to a share,
  a chat, a session, a task or a conversation, with an id in it: the footer's second line, read by
  the path, not the host. A path word with no id after it (`/code/README`, `/docs/session-handling`)
  is a page, not a session.

A mention is not a credit: inside a sentence, or quoted in a backtick, it opens no line. The owner
may allow one line, as written, by adding it to ALLOWED with who allowed it, when and why.

Exit 0 when nothing is refused, 1 when a line is, 2 when the input cannot be read — no verdict, said
out loud.

Role: decider — it answers pass or fail and returns an exit code that can block a pull request.
"""

from __future__ import annotations

import argparse
import pathlib
import re
import subprocess
import sys

__all__ = ["ALLOWED", "CREDIT_VERBS", "check_text", "commits_in_range", "is_credit_key", "main", "names_a_tool", "parse_log", "trailer_block"]

# a `git` that never answers must not eat the job's whole budget (as in lint_commits.py)
LOCAL_TIMEOUT_SECONDS = 60

# Lines the owner allowed, exactly as written, stripped of surrounding space.
# line · who allowed it · when · why
ALLOWED: tuple[str, ...] = ()

# the verbs a footer credits with, before `with` or `by`
CREDIT_VERBS = (
    "generated", "co-authored", "coauthored", "authored", "written", "drafted", "created", "made",
    "produced", "built", "developed", "implemented", "assisted", "composed", "crafted", "powered",
    "coded", "vibe-coded", "paired", "designed",
)
# a Thai verb and its "with" or "by", written without a space, as Thai is
THAI_CREDIT = r"(?:สร้าง|เขียน|ร่าง|พัฒนา|ผลิต|ทำ|ช่วยเขียน)(?:ขึ้น)?\s*(?:ด้วย|โดย|จาก)\s*"
# a lower-case word that opens a phrase, not a name: "generated by the build", "made by hand"
NOT_A_NAME = frozenset({"the", "a", "an", "this", "that", "these", "those", "our", "my", "your", "its", "their",
                        "his", "her", "hand", "default", "design", "me", "us", "you", "them", "it"})
# the words a trailer key credits with, as one part of the key: `AI-Assistant`, `Agent`, `Model-Used`
CREDIT_KEY_PARTS = frozenset({"ai", "assistant", "agent", "model", "llm", "bot", "copilot"})

# what may stand before the words on the line: emoji, list marks, emphasis — but not a backtick,
# which makes the line a quotation of the credit rather than the credit
_LEAD = r"^(?::[a-z0-9_+-]+:|[^\w`])*"
TRAILER = re.compile(_LEAD + r"([A-Za-z][\w-]*)\s*:(?!//)")
_EN_VERB = r"(?:" + "|".join(re.escape(verb) for verb in CREDIT_VERBS) + r")\s+(?:with|by|using|via)\s*:?\s*"
_VERB = r"(?:" + _EN_VERB + "|" + THAI_CREDIT + r"(?=[A-Za-z\[*_]))"
CREDIT = re.compile(_LEAD + _VERB + r"[*_~\"'(]*(?P<name>\S.*)$", re.IGNORECASE)
# the verb alone, its name on the next line: "Generated by" / "Some Tool"
CREDIT_OPEN = re.compile(_LEAD + _EN_VERB + r"$|" + _LEAD + THAI_CREDIT + r"$", re.IGNORECASE)
LINK_LINE = re.compile(
    r"^(?::[a-z0-9_+-]+:|[^\w`\[<])*(?:[A-Za-z][\w-]*\s*:\s+)?(?:\[[^\]]*\]\(\s*<?(?P<md>https?://[^\s)>]+)>?\s*\)|<?(?P<url>https?://\S+?)>?)\s*$",
    re.IGNORECASE,
)
SESSION_PATH = re.compile(
    r"/(?:share|s|c|chat|chats|code|session|sessions|conversation|conversations|thread|threads|task|tasks|agent|agents)/(?=[^/?#]*\d)[^/?#]{5,}"
    r"|/[^/?#]*(?:session|task)[^/?#]*\d",
    re.IGNORECASE,
)


def is_credit_key(key: str) -> bool:
    """Whether a trailer key credits somebody — every `-by` and `-with` but the signer's own line."""
    lower = key.lower()
    if lower == "signed-off-by":
        return False
    return (lower.endswith(("-by", "-with")) or any(word in lower for word in ("session", "generated", "assisted", "co-author", "coauthor"))
            or bool(CREDIT_KEY_PARTS.intersection(re.split(r"[-_]", lower))))


def names_a_tool(name: str) -> bool:
    """Whether what follows a credit verb is a name: anything but a path or a phrase opening with an article."""
    text = name.lstrip("*_~\"'(")
    if text.startswith("["):  # a link's text is a name, whatever its target: "Generated with [Some Tool](…)"
        return True
    first = text.split()[0].rstrip(".,;:!?*_~\"')") if text.split() else ""
    if not first or "/" in first or re.search(r"\.\w{1,4}$", first) and not first[0].isupper():
        return False
    return first[0].isupper() or not first.isascii() or first.lower() not in NOT_A_NAME


def trailer_block(message: str, subject: bool = False) -> str:
    """The message's last paragraph — where `git commit -s` writes the sign-off and git
    reads trailers. A `Signed-off-by:` line in the middle of the body ("the shape is
    `Signed-off-by: …`, for example") is text, not a signature. `subject` says the
    message still opens with its subject line, which is never a trailer.
    """
    lines = message.splitlines()[1:] if subject else message.splitlines()
    lines = [line for line in lines if not line.startswith("#")]  # git's own comment lines
    while lines and not lines[-1].strip():
        lines.pop()
    for at in range(len(lines) - 1, -1, -1):
        if not lines[at].strip():
            return "\n".join(lines[at + 1:])
    return "\n".join(lines)


def _name(rest: str) -> str:
    """The name a credit line gives, without the link, emphasis or quote marks around it."""
    return re.split(r"[\]()*_~\"']|\s[-—·|]\s", rest.strip(" [*_~\"'"), maxsplit=1)[0].strip()


def check_text(text: str | None) -> list[tuple[int, str]]:
    """Every refused line, as (line number, why). An empty text passes: it credits nobody."""
    problems = []
    lines = re.split(r"\r\n|\r|\n", text or "")  # a bare CR ends a line too: a terminal shows it as one
    for number, line in enumerate(lines, start=1):
        if line.strip() in ALLOWED:
            continue
        if CREDIT_OPEN.match(line):  # the name on the next line that holds anything
            after = next((later for later in lines[number:] if later.strip()), "")
            line = line.rstrip() + " " + after.strip()
        trailer, credit, link = TRAILER.match(line), CREDIT.match(line), LINK_LINE.match(line)
        if trailer and is_credit_key(trailer.group(1)):
            problems.append((number, f"opens with a `{trailer.group(1)}:` trailer — credit goes to the person who signed, alone"))
        elif credit and names_a_tool(credit.group("name")):
            problems.append((number, f"credits {_name(credit.group('name'))} — a tool that helped write a change is not its author"))
        elif link and SESSION_PATH.search("/" + (link.group("md") or link.group("url")).split("//", 1)[1].partition("/")[2].partition("#")[0]):
            problems.append((number, "is a link to an assistant's session — the description stands on its own"))
    return problems


# A message holds newlines, so a record ends at a byte no message holds; the same choice, for the
# same reason, as lint_commits.py makes.
RECORD_SEP = "\x1e"
FIELD_SEP = "\x00"
LOG_FORMAT = "%H%x00%B%x1e"


def parse_log(out: str) -> list[tuple[str, str]]:
    """Turn `git log --format=LOG_FORMAT` output into (short sha, message)."""
    return [
        (sha[:9], message)
        for chunk in out.split(RECORD_SEP)
        if chunk.strip()
        for sha, message in [chunk.strip("\n").split(FIELD_SEP, 1)]
    ]


def commits_in_range(rev_range: str) -> list[tuple[str, str]]:
    """The commits in this range, merge commits excluded. A range git cannot read, or does not
    answer for in time, is a RuntimeError that says so: no verdict on anybody's commits."""
    try:
        out = subprocess.run(  # the range comes from CI or the developer, never from a commit
            ["git", "log", "--no-merges", f"--format={LOG_FORMAT}", rev_range],
            capture_output=True,
            check=True,
            timeout=LOCAL_TIMEOUT_SECONDS,
        ).stdout
    except subprocess.TimeoutExpired as expired:
        raise RuntimeError(f"`git log {rev_range}` did not answer within {LOCAL_TIMEOUT_SECONDS} seconds") from expired
    except subprocess.CalledProcessError as failed:
        raise RuntimeError(f"`git log {rev_range}` failed: {failed.stderr.decode('utf-8', 'replace').strip()}") from failed
    # a message is bytes; one that is not UTF-8 is carried through and read as it is
    return parse_log(out.decode("utf-8", "surrogateescape"))


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    group = parser.add_mutually_exclusive_group(required=True)
    group.add_argument("--range", dest="rev_range", help="a commit range, as `git log` takes one")
    group.add_argument("--file", type=pathlib.Path, help="one text to read: a description, a commit message")
    args = parser.parse_args(argv)

    failures: list[tuple[str, int, str]] = []
    if args.file is not None:
        try:
            text = args.file.read_text(encoding="utf-8")
        except (OSError, UnicodeDecodeError) as unreadable:
            print(f"cannot read {args.file}: {unreadable}", file=sys.stderr)
            return 2
        failures.extend(("", number, why) for number, why in check_text(text))
    else:
        try:
            commits = commits_in_range(args.rev_range)
        except RuntimeError as unreadable:
            print(f"cannot read the history: {unreadable}", file=sys.stderr)
            return 2
        for sha, message in commits:
            failures.extend((sha, number, why) for number, why in check_text(message))

    for sha, number, why in failures:
        where = f"{sha}: line {number}" if sha else f"line {number}"
        print(f"FAIL {where} {why}".encode("utf-8", "backslashreplace").decode("utf-8"))
    if not failures:
        print("no line credits anybody who did not sign")
    return 1 if failures else 0


if __name__ == "__main__":
    sys.exit(main())
