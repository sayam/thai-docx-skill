"""A line that credits a tool for a change is refused by its shape, not by the tool's name (ADR 0013).

Gates `credit-lines-read-by-shape` and `credit-line-checker-proven-two-way`. On 2026-10-14 a
footer naming a tool the description check had not been told of passed it, and a "Generated with"
line in a commit body passed the commit check, which knows two trailer keys (V35-07). The checker
reads the shape every footer has: a trailer whose key is a credit, a credit verb and `with` or `by`
before a name, a link alone on its line to a session. What it must not refuse is a mention — inside a
sentence, in a backtick, a path after the verb — and the signer's own line.
"""

