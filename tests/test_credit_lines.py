def test_a_credit_split_over_two_lines_is_one_credit():
    """The verb on one line and the name on the next one that holds anything, as a footer wraps."""
    assert [n for n, _ in lint_credit_lines.check_text("body\nGenerated by\n\nSome Tool")] == [2]
    assert lint_credit_lines.check_text("body\nGenerated by\nthe build") == []


@pytest.mark.parametrize("line", REFUSED)
def test_a_credit_is_refused_by_its_shape_whatever_the_tool_is_called(line):
    problems = lint_credit_lines.check_text("body\n" + line + "\nmore")
    assert [n for n, _ in problems] == [2], (line, problems)
    assert lint_credit_lines.check_text("x\r\n" + line) == [(2, problems[0][1])], "CRLF is the platform's editor"


@pytest.mark.parametrize("line", PASSES)
def test_a_mention_a_path_and_the_signer_s_own_line_pass(line):
    assert lint_credit_lines.check_text(line) == [], line
    assert lint_credit_lines.check_text(None) == []


def test_the_reason_names_the_line_s_kind_and_the_name_it_gives():
    footer, trailer, link = (lint_credit_lines.check_text(t)[0][1] for t in (
        "🤖 Generated with [Some Tool](https://example.invalid)", "Assisted-by: Some Tool", "https://example.invalid/share/1a2b3c4d"))
    assert footer.startswith("credits Some Tool —")
    assert trailer.startswith("opens with a `Assisted-by:` trailer")
    assert "link to an assistant's session" in link


def test_an_allowed_line_passes_as_written_and_not_otherwise(monkeypatch):
    line = "Generated with Some Tool"
    monkeypatch.setattr(lint_credit_lines, "ALLOWED", (line,))
    assert lint_credit_lines.check_text("  " + line + "  ") == []
    assert lint_credit_lines.check_text(line + " and more") == [(1, lint_credit_lines.check_text(line + " and more")[0][1])]
    monkeypatch.setattr(lint_credit_lines, "ALLOWED", ())
    assert lint_credit_lines.check_text(line)


def _git(cwd: pathlib.Path, *args: str) -> str:
    env = {
        **os.environ, "GIT_CONFIG_GLOBAL": os.devnull, "GIT_CONFIG_NOSYSTEM": "1",
        "GIT_AUTHOR_NAME": "Example", "GIT_AUTHOR_EMAIL": "a@example.invalid",
        "GIT_COMMITTER_NAME": "Example", "GIT_COMMITTER_EMAIL": "a@example.invalid",
    }
    done = subprocess.run(["git", "-c", "commit.gpgsign=false", "-c", f"core.hooksPath={cwd / 'no-hooks'}", *args],
                          cwd=cwd, capture_output=True, text=True, timeout=60, check=True, env=env)
    return done.stdout.strip()


def _run(args: list[str], cwd: pathlib.Path) -> subprocess.CompletedProcess:
    return subprocess.run([sys.executable, str(TOOL), *args], cwd=cwd, capture_output=True, text=True, timeout=120)


def test_a_planted_branch_names_the_commit_and_the_line_and_a_clean_one_passes(tmp_path):
    repo = tmp_path / "repo"
    repo.mkdir()
    (repo / "no-hooks").mkdir()
    _git(repo, "init", "-q", "-b", "main")
    (repo / "a.txt").write_text("a\n", encoding="utf-8")
    _git(repo, "add", "a.txt")
    _git(repo, "commit", "-q", "-m", "feat: a thing\n\nSigned-off-by: Example <a@example.invalid>")
    _git(repo, "checkout", "-q", "-b", "topic")
    (repo / "a.txt").write_text("b\n", encoding="utf-8")
    _git(repo, "commit", "-q", "-am", "fix: a clean one\n\nSays what it does.\n\nSigned-off-by: Example <a@example.invalid>")
    clean = _run(["--range", "main..HEAD"], repo)
    assert clean.returncode == 0 and "no line credits anybody" in clean.stdout, clean
    (repo / "a.txt").write_text("c\n", encoding="utf-8")
    _git(repo, "commit", "-q", "-am", "fix: a credited one\n\nGenerated with Some Tool\n\nSigned-off-by: Example <a@example.invalid>")
    sha = _git(repo, "rev-parse", "--short=9", "HEAD")
    red = _run(["--range", "main..HEAD"], repo)
    assert red.returncode == 1 and red.stderr == "", red
    assert f"FAIL {sha}: line 3 credits Some Tool" in red.stdout, red.stdout
    assert red.stdout.count("FAIL") == 1, "the clean commit is not named"
    # a range git cannot read is no verdict on anybody's commits
    unreadable = _run(["--range", "nowhere..HEAD"], repo)
    assert unreadable.returncode == 2 and "cannot read the history" in unreadable.stderr and unreadable.stdout == ""


def test_the_command_reads_a_file_and_says_which_line(tmp_path):
    path = tmp_path / "description.md"
    path.write_text("One.\n\n🤖 Generated with [Some Tool](https://example.invalid)\n\nhttps://example.invalid/share/x1y2z3\n", encoding="utf-8")
    red = _run(["--file", str(path)], tmp_path)
    assert red.returncode == 1 and "FAIL line 3 credits Some Tool" in red.stdout and "FAIL line 5 is a link" in red.stdout
    path.write_text("Fixes the caption.\n", encoding="utf-8")
    assert _run(["--file", str(path)], tmp_path).returncode == 0
    missing = _run(["--file", str(tmp_path / "missing.md")], tmp_path)
    assert missing.returncode == 2 and "cannot read" in missing.stderr
    assert _run([], tmp_path).returncode == 2, "silence is not a pass"


def test_the_commits_job_and_the_description_check_run_the_checker():
    """One shape, read in both places a change is published under the signer's name."""
    jobs = yaml.safe_load(GATES.read_text(encoding="utf-8"))["jobs"]
    runs = "\n".join(str(step.get("run", "")) for step in jobs["commits"]["steps"])
    assert 'python3 tools/lint_credit_lines.py --range "$range"' in runs.split("\n")
    assert runs.index("lint_commits.py") < runs.index("lint_credit_lines.py")
    # the description check is the same function, so a tool it was never told of is refused there too
    assert lint_pr_body.check_body("Generated with Some Tool") == lint_credit_lines.check_text("Generated with Some Tool") != []


def test_a_line_of_shortcode_colons_is_read_in_linear_time():
    """A colon opens a `:shortcode:` or stands alone, never both: read both ways, a line of `:+:`
    repeated backtracked exponentially (CodeQL py/redos). Run apart, so a regression times out."""
    code = f"import sys; sys.path.insert(0, {str(ROOT / 'tools')!r}); import lint_credit_lines as l; l.check_text(':+:' * 200 + chr(0))"
    subprocess.run([sys.executable, "-c", code], check=True, timeout=10)
